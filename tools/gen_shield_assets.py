"""
シールド用アセット生成スクリプト

出力:
  project/Resources/Models/shield/shield_hex_tile.obj / .mtl   … 六角形タイル 1 枚
  project/Resources/Textures/shield_hex.png                    … タイルの縁取りテクスチャ

仕組み:
  - タイルは外接円半径 1 の正六角形。ローカル +Z が表面の外向き（法線）、角の 1 つが +X
  - 中心から扇状に三角形分割し、UV の u を「中心=0 / 縁=1」にする
    → テクスチャは横方向のグラデーションだけで、縁が光る六角形になる
  - 球面上の配置（ゴールドバーグ多面体のセル中心）は ShieldEffect.cpp が実行時に計算し、
    セル 1 個ずつをインスタンス描画で個別に動かす

使い方:  python tools/gen_shield_assets.py
"""

import math
import os
import struct
import zlib

TEX_W, TEX_H = 256, 8

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "project", "Resources")
MODEL_DIR = os.path.join(ROOT, "Models", "shield")
TEX_DIR = os.path.join(ROOT, "Textures")


def write_tile():
    os.makedirs(MODEL_DIR, exist_ok=True)
    corners = [(math.cos(math.radians(60 * i)), math.sin(math.radians(60 * i))) for i in range(6)]
    lines = ["# generated by tools/gen_shield_assets.py",
             "mtllib shield_hex_tile.mtl",
             "o shield_hex_tile",
             "v 0.000000 0.000000 0.000000"]
    for x, y in corners:
        lines.append("v %.6f %.6f 0.000000" % (x, y))
    lines += ["vt 0.000000 0.500000", "vt 1.000000 0.500000", "vn 0.000000 0.000000 1.000000",
              "usemtl shield", "s off"]
    for i in range(6):
        a, b = 2 + i, 2 + (i + 1) % 6
        lines.append("f 1/1/1 %d/2/1 %d/2/1" % (a, b))
    with open(os.path.join(MODEL_DIR, "shield_hex_tile.obj"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(MODEL_DIR, "shield_hex_tile.mtl"), "w", newline="\n") as f:
        f.write("# generated by tools/gen_shield_assets.py\n"
                "newmtl shield\n"
                "Ka 1.000000 1.000000 1.000000\n"
                "Kd 1.000000 1.000000 1.000000\n"
                "d 1.000000\n"
                "illum 1\n"
                "map_Kd shield_hex.png\n")


def smoothstep(e0, e1, x):
    t = max(0.0, min(1.0, (x - e0) / (e1 - e0)))
    return t * t * (3.0 - 2.0 * t)


def hex_alpha(u):
    fill = 0.12 + 0.22 * u * u                                            # 中心は薄く、縁へ向かって濃く
    rim = smoothstep(0.70, 0.88, u) * (1.0 - smoothstep(0.92, 0.99, u))  # 縁の発光ライン
    return max(fill, rim) * (1.0 - smoothstep(0.97, 1.0, u))


def write_png():
    os.makedirs(TEX_DIR, exist_ok=True)
    raw = bytearray()
    for _ in range(TEX_H):
        raw.append(0)
        for x in range(TEX_W):
            u = (x + 0.5) / TEX_W
            raw += bytes((255, 255, 255, int(round(hex_alpha(u) * 255))))

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", TEX_W, TEX_H, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    with open(os.path.join(TEX_DIR, "shield_hex.png"), "wb") as f:
        f.write(png)


if __name__ == "__main__":
    write_tile()
    write_png()
    print("wrote shield_hex_tile.obj / shield_hex.png")
